package io.github.baeseungwon1010.officecanvas.hwp

import io.github.baeseungwon1010.officecanvas.DocumentFormat
import io.github.baeseungwon1010.officecanvas.OfficeCanvas
import io.github.baeseungwon1010.officecanvas.hwpx.HwpxElement
import io.github.baeseungwon1010.officecanvas.hwpx.HwpxRenderer
import io.github.baeseungwon1010.officecanvas.hwpx.ParaAlign
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.RuntimeEnvironment
import org.robolectric.annotation.Config
import org.robolectric.annotation.GraphicsMode
import java.io.File

/**
 * sample_hwpml.hwp is generated by tools/make_sample_hwpml.py. HWPML saves no
 * layout, so these check the layout made here: lines broken inside the body,
 * line breaks, tables in the text and placed by offsets, page breaks.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
@GraphicsMode(GraphicsMode.Mode.NATIVE)
class HwpmlParserTest {

    private val file by lazy { File(javaClass.classLoader!!.getResource("hwp_samples/sample_hwpml.hwp")!!.toURI()) }
    private val doc by lazy { HwpmlParser.parse(file) }

    private val bodyW = 59528L - 8504 - 8504

    private fun runs(page: Int) = doc.pages[page].elements.filterIsInstance<HwpxElement.TextRun>()

    @Test
    fun `is detected as HWP by content`() {
        assertEquals(DocumentFormat.HWP, DocumentFormat.detect(file))
        assertTrue(HwpmlParser.isHwpml(file))
    }

    @Test
    fun `long paragraphs wrap inside the body, each line within its width`() {
        val lines = runs(0).filter { it.text.isNotBlank() }
        assertTrue("${lines.size} lines", lines.size >= 5)
        for (line in lines) {
            assertTrue(line.text, line.xHu + line.widthHu <= bodyW)
            val natural = line.spans.sumOf { HwpxRenderer.widthHu(it.copy(text = it.text.trimEnd())).toDouble() }
            assertTrue("${line.text}: $natural > ${line.widthHu}", natural <= line.widthHu + 1)
        }
        // A Latin word is never cut in two.
        assertTrue(lines.none { it.text.trimEnd().endsWith("paginatio") || it.text.trimEnd().endsWith("layou") })
        // Lines go down, one after another.
        val ys = lines.map { it.yHu }
        assertEquals(ys.sorted(), ys)
        assertEquals(ys.size, ys.toSet().size)
    }

    @Test
    fun `the title is centered and bold, and the body justified`() {
        val title = runs(0).first()
        assertEquals("HWPML 견본", title.text)
        assertEquals(ParaAlign.CENTER, title.align)
        assertTrue(title.spans.first().style.bold)
        assertEquals(16f, title.sizePt)
        assertEquals(ParaAlign.JUSTIFY, runs(0)[1].align)
    }

    @Test
    fun `a line break starts a new line`() {
        val first = runs(0).single { it.text == "첫 줄" }
        val after = runs(0).single { it.text == "줄바꿈 뒤" }
        assertTrue(after.yHu > first.yHu)
    }

    @Test
    fun `a table in the text keeps its thin empty row, and one placed by offsets goes there`() {
        val tables = doc.pages[0].elements.filterIsInstance<HwpxElement.Table>()
        val inline = tables.single { it.cells.size == 3 }
        assertEquals(400L, inline.rowHeightsHu[1])
        assertTrue(inline.rowHeightsHu[0] >= 2000)
        val placed = tables.single { it.cells.size == 1 }
        // Offsets from the page corner; positions here are from the body's.
        assertEquals(30000L - 8504, placed.xHu)
        assertEquals(60000L - (5668 + 4252), placed.yHu)
    }

    @Test
    fun `a page break starts a page, and a full page runs on to the next`() {
        assertTrue("${doc.pages.size} pages", doc.pages.size >= 3)
        assertEquals("둘째 쪽", runs(1).first().text)
        val bodyH = 84188L - (5668 + 4252) - (4252 + 4252)
        for (page in doc.pages) for (line in page.elements.filterIsInstance<HwpxElement.TextRun>())
            assertTrue("${line.text} at ${line.yHu}", line.yHu + line.heightHu <= bodyH)
    }

    @Test
    fun `renders through OfficeCanvas`() {
        var pages = 0
        OfficeCanvas.render(RuntimeEnvironment.getApplication(), file, 800) { _, bmp -> pages++; bmp.recycle() }
        assertEquals(doc.pages.size, pages)
    }
}
