package io.github.baeseungwon1010.officecanvas.docx

import io.github.baeseungwon1010.officecanvas.DocumentFormat
import io.github.baeseungwon1010.officecanvas.OfficeCanvas
import io.github.baeseungwon1010.officecanvas.hwpx.DrawingKind
import io.github.baeseungwon1010.officecanvas.hwpx.HwpxElement
import io.github.baeseungwon1010.officecanvas.hwpx.HwpxRenderer
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.RuntimeEnvironment
import org.robolectric.annotation.Config
import org.robolectric.annotation.GraphicsMode
import java.io.File

/**
 * sample.docx is generated by tools/make_sample_docx.py (python-docx). Word saves
 * no layout, so these check the layout made here from its styles, lists, tables,
 * picture, page break, header and footer.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
@GraphicsMode(GraphicsMode.Mode.NATIVE)
class DocxParserTest {

    private val file by lazy { File(javaClass.classLoader!!.getResource("docx_samples/sample.docx")!!.toURI()) }
    private val doc by lazy { DocxParser.parse(file) }

    /** A4 with 2.5 cm margins, in HWPUNIT. */
    private val bodyWidth = (21.0 - 5.0) / 2.54 * 7200

    private fun runs(page: Int) = doc.pages[page].elements.filterIsInstance<HwpxElement.TextRun>()
    private fun run(text: String) = doc.pages.flatMap { it.elements }.filterIsInstance<HwpxElement.TextRun>().first { it.text.startsWith(text) }

    @Test
    fun `is detected as DOCX by content`() {
        assertEquals(DocumentFormat.DOCX, DocumentFormat.detect(file))
    }

    @Test
    fun `styles give the title and headings their size, weight and color`() {
        val title = run("DOCX sample")
        assertEquals(26f, title.sizePt)
        val heading = run("1. Text")
        assertTrue(heading.spans.first().style.bold)
        assertEquals(14f, heading.sizePt)
        // Heading 1 in python-docx's template is a dark blue.
        val c = heading.spans.first().style.colorArgb
        assertTrue(Integer.toHexString(c), (c and 0xFF) > ((c shr 16) and 0xFF))
        // The title style draws a line under itself.
        assertTrue(doc.pages[0].elements.filterIsInstance<HwpxElement.Drawing>().any { it.kind == DrawingKind.LINE && it.yHu > title.yHu })
    }

    /** The lines of page 1 between two others (by position). */
    private fun linesBetween(after: String, before: String): List<HwpxElement.TextRun> {
        val top = run(after).yHu
        val bottom = run(before).yHu
        return runs(0).filter { it.yHu in (top + 1) until bottom }.sortedBy { it.yHu }
    }

    @Test
    fun `a long paragraph wraps inside the body, each line fitting its width`() {
        val lines = linesBetween("1. Text", "Bold")
        assertTrue("${lines.size} lines", lines.size >= 3)
        for (line in lines) {
            assertTrue(line.xHu + line.widthHu <= bodyWidth + 20)
            val natural = line.spans.sumOf { HwpxRenderer.widthHu(it.copy(text = it.text.trimEnd())).toDouble() }
            assertTrue("${line.text}: $natural > ${line.widthHu}", natural <= line.widthHu + 1)
        }
    }

    @Test
    fun `runs keep their own bold, italic and color`() {
        val spans = run("Bold").spans
        assertTrue(spans.first { it.text.startsWith("Bold") }.style.bold)
        assertTrue(spans.first { it.text.startsWith("italic") }.style.italic)
        assertEquals(0xFFC00000.toInt(), spans.first { it.text.startsWith("red") }.style.colorArgb)
    }

    @Test
    fun `lists are numbered and bulleted, the text after a tab to the indent`() {
        assertEquals(listOf("1.", "2.", "3."), listOf("First", "Second", "Third").map { w ->
            runs(0).first { it.text.endsWith("$w step") }.spans.first().text
        })
        val bullet = runs(0).first { it.text.endsWith("A bullet") }
        assertEquals("•", bullet.spans.first().text)
        assertNotNull(bullet.spans[1].tabHu)
    }

    @Test
    fun `a right tab stop puts the text after it against the stop`() {
        val line = run("Left")
        val tab = line.spans.first { it.tabHu != null }.tabHu!!
        val left = HwpxRenderer.widthHu(line.spans.first().copy(text = "Left"))
        val right = HwpxRenderer.widthHu(line.spans.last().copy(text = "Right"))
        // The stop is 16 cm from the margin.
        assertEquals(16 / 2.54 * 7200, (left + tab + right).toDouble(), 50.0)
    }

    @Test
    fun `paragraph borders and shading are drawn`() {
        val drawings = doc.pages[0].elements.filterIsInstance<HwpxElement.Drawing>()
        val under = run("A paragraph with a line")
        assertTrue(drawings.any { it.kind == DrawingKind.LINE && it.lineArgb == 0xFF2E75B6.toInt() && it.yHu > under.yHu })
        assertTrue(drawings.any { it.kind == DrawingKind.RECTANGLE && it.fillArgb == 0xFFFFF2CC.toInt() })
    }

    @Test
    fun `one and a half line spacing spaces lines further apart`() {
        val single = linesBetween("1. Text", "Bold").map { it.yHu }
        val spaced = linesBetween("A shaded", "한글").map { it.yHu }
        assertTrue(spaced.size >= 2)
        // python-docx's Normal style is 1.15 lines, so 1.5 lines is 1.5 / 1.15 of it.
        assertEquals(1.5 / 1.15, (spaced[1] - spaced[0]).toDouble() / (single[1] - single[0]), 0.03)
    }

    @Test
    fun `a table takes its grid, merged cells and shading`() {
        val table = doc.pages.flatMap { it.elements }.filterIsInstance<HwpxElement.Table>().single()
        assertEquals(3, table.columnWidthsHu.size)
        assertEquals(2, table.cells[0][0]!!.colSpan)
        assertEquals(3, table.cells[1][2]!!.rowSpan)
        assertEquals(0xFFD9E2F3.toInt(), table.cells[2][0]!!.borderFill!!.fillArgb)
        // Table Grid: lines all round; its paragraph spacing (none after) applies in it.
        assertNotNull(table.cells[0][0]!!.borderFill!!.top)
        assertTrue(table.rowHeightsHu[3] < 1600)
    }

    @Test
    fun `a heading kept with the next paragraph goes with the picture onto page two`() {
        val page2 = doc.pages[1].elements
        val image = page2.filterIsInstance<HwpxElement.ImageEl>().single()
        assertEquals(6 / 2.54 * 7200, image.widthHu.toDouble(), 20.0)
        assertTrue("read from the package when drawn", image.bytes!!()!!.size > 100)
        assertEquals("3. Picture", runs(1).filter { it.yHu >= 0 }.minByOrNull { it.yHu }!!.text)
    }

    @Test
    fun `a page break starts a page, and the header and footer repeat with the page number`() {
        assertEquals(3, doc.pages.size)
        assertTrue(runs(2).any { it.text.startsWith("After the page break") })
        for ((i, _) in doc.pages.withIndex()) {
            assertTrue(runs(i).any { it.text == "OfficeCanvas sample header" && it.yHu < 0 })
            assertTrue(runs(i).any { it.text == "Page ${i + 1}" })
        }
    }

    @Test
    fun `renders through OfficeCanvas`() {
        var pages = 0
        OfficeCanvas.render(RuntimeEnvironment.getApplication(), file, 800) { _, bmp -> pages++; bmp.recycle() }
        assertEquals(3, pages)
    }

    @Test
    fun `list numbers follow Word's formats`() {
        assertEquals("iv", DocxParser.numberText(4, "lowerRoman"))
        assertEquals("AA", DocxParser.numberText(27, "upperLetter"))
        assertEquals("다", DocxParser.numberText(3, "ganada"))
        assertEquals("②", DocxParser.numberText(2, "decimalEnclosedCircle"))
        assertEquals("십이", DocxParser.numberText(12, "koreanDigital"))
    }
}
