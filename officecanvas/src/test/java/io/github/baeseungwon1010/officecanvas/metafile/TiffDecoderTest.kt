package io.github.baeseungwon1010.officecanvas.metafile

import android.graphics.BitmapFactory
import android.graphics.Color
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import org.robolectric.annotation.GraphicsMode
import java.io.File

/** tiff_samples/ were written by PIL: a 40x30 image, left half red, right half blue,
 *  in each compression/color layout the decoder claims to support (the bilevel
 *  one white and black). Generated by tools/make_small_fixtures.py. */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
@GraphicsMode(GraphicsMode.Mode.NATIVE)
class TiffDecoderTest {

    private fun decode(name: String) = File(javaClass.classLoader!!.getResource("tiff_samples/$name")!!.toURI()).readBytes()
        .let { TiffDecoder.toBmp(it) }
        ?.let { BitmapFactory.decodeByteArray(it, 0, it.size) }

    @Test
    fun `rgb tiffs in every supported compression decode with the right pixels`() {
        for (name in listOf("rgb_raw.tif", "rgb_tiff_lzw.tif", "rgb_packbits.tif", "palette_lzw.tif")) {
            val bmp = decode(name)
            assertNotNull(name, bmp)
            assertEquals(name, 40, bmp!!.width)
            assertEquals(name, 30, bmp.height)
            assertEquals("$name left half", Color.RED, bmp.getPixel(5, 15))
            assertEquals("$name right half", Color.BLUE, bmp.getPixel(35, 15))
        }
    }

    @Test
    fun `gray and bilevel tiffs decode`() {
        val gray = decode("gray_raw.tif")!!
        assertEquals(Color.red(gray.getPixel(5, 5)), Color.green(gray.getPixel(5, 5)))
        val bilevel = decode("bilevel_packbits.tif")!!
        assertEquals(Color.WHITE, bilevel.getPixel(5, 5))
        assertEquals(Color.BLACK, bilevel.getPixel(35, 5))
    }
}
