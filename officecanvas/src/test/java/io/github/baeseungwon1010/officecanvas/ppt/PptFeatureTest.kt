package io.github.baeseungwon1010.officecanvas.ppt

import android.graphics.Bitmap
import android.graphics.Color
import io.github.baeseungwon1010.officecanvas.slide.Element
import io.github.baeseungwon1010.officecanvas.slide.PathOp
import io.github.baeseungwon1010.officecanvas.slide.SlideRenderer
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import org.robolectric.annotation.GraphicsMode
import java.io.File
import java.io.FileOutputStream

/**
 * feature_test.ppt is generated by tools/make_feature_deck.py (python-pptx) and
 * converted to binary .ppt by LibreOffice, so each slide exercises one parser
 * feature with known content; LibreOffice's own PDF render of it was the visual
 * reference while writing these.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
@GraphicsMode(GraphicsMode.Mode.NATIVE)
class PptFeatureTest {

    private val file: File by lazy {
        File(javaClass.classLoader!!.getResource("ppt_samples/feature_test.ppt")!!.toURI())
    }
    private val deck by lazy { PptParser.parse(file) }

    private fun shapes(slide: Int) = deck.slides[slide - 1].elements.filterIsInstance<Element.Shape>()

    @Test
    fun `auto-numbered paragraphs get their numbers, restarting after a plain line`() {
        val paragraphs = shapes(1).mapNotNull { it.text }.flatMap { it.paragraphs }
        val bullets = paragraphs.associate { it.plainText to it.bullet }
        assertEquals("1.", bullets["First"])
        assertEquals("2.", bullets["Second"])
        assertEquals("3.", bullets["Third"])
        assertEquals(null, bullets["Plain line"])
        assertEquals("a.", bullets["Alpha one"])
        assertEquals("b.", bullets["Alpha two"])
    }

    @Test
    fun `freeform and preset shapes carry real outlines`() {
        val outlined = shapes(2).filter { it.outline != null }
        assertEquals("freeform + triangle + diamond + arrow + star", 5, outlined.size)
        // The freeform is a triangle: move + two lines + close.
        val freeform = outlined.first { o -> o.outline!!.count { it is PathOp.LineTo } == 2 }
        assertTrue(freeform.outline!!.last() is PathOp.Close)
        assertEquals(Color.RED, freeform.fillArgb)
    }

    @Test
    fun `linear and axial gradients run in the right direction`() {
        val (horizontal, vertical) = shapes(3).mapNotNull { it.gradient }
        // red on the left -> blue on the right
        assertEquals(Color.RED, horizontal.colors.first())
        assertEquals(Color.BLUE, horizontal.colors.last())
        assertEquals(0f, ((horizontal.angleDeg % 360) + 360) % 360, 0.5f)
        // green at the bottom -> yellow at the top: runs upward
        assertEquals(0xFF00A000.toInt(), vertical.colors.first())
        assertEquals(270f, ((vertical.angleDeg % 360) + 360) % 360, 0.5f)

        // The slide's own background gradient comes first, as a full-slide shape.
        val background = shapes(5).first()
        assertEquals(deck.widthEmu, background.box.w)
        assertNotNull(background.gradient)
        val (axial, radial) = shapes(5).drop(1).mapNotNull { it.gradient }
        assertEquals(listOf(Color.BLUE, Color.WHITE, Color.BLUE), axial.colors)
        assertTrue(radial.radial)
        assertEquals(Color.WHITE, radial.colors.first())
        assertEquals(Color.RED, radial.colors.last())
    }

    @Test
    fun `picture crop, sub-superscript and monospace font are read`() {
        val pictures = deck.slides[3].elements.filterIsInstance<Element.Picture>()
        val cropped = pictures.firstOrNull { it.crop != null }
        assertNotNull(cropped)
        assertEquals(0.5f, cropped!!.crop!!.left, 0.01f)

        val runs = shapes(4).mapNotNull { it.text }.flatMap { it.paragraphs }.flatMap { it.runs }
        assertTrue("superscript 2", runs.any { it.text == "2" && it.baselinePercent > 0 })
        assertTrue("subscript 2", runs.any { it.text == "2" && it.baselinePercent < 0 })
        assertTrue("Courier New run", runs.any { it.fontFamily == "Courier New" })
    }

    @Test
    fun `hyperlinks take the scheme's hyperlink color and an underline`() {
        val runs = shapes(4).mapNotNull { it.text }.flatMap { it.paragraphs }.flatMap { it.runs }
        val link = runs.single { it.text == "example.org" }
        val plain = runs.single { it.text == "see " }
        assertTrue(link.underline)
        assertFalse(plain.underline)
        assertNotEquals(plain.colorArgb, link.colorArgb)
    }

    @Test
    fun `renders every feature slide`() {
        val out = File("build/ppt_render_check").apply { mkdirs() }
        var n = 0
        SlideRenderer.render(deck, file, targetLongSidePx = 600) { i, bmp: Bitmap ->
            FileOutputStream(File(out, "feature_${i + 1}.png")).use { bmp.compress(Bitmap.CompressFormat.PNG, 100, it) }
            // Cropped picture keeps the right (blue) half of a red|blue image.
            if (i == 3) {
                val c = bmp.getPixel((0.5f / 10 * 600 + 20).toInt(), (2.0f / 10 * 600).toInt())
                assertEquals("cropped picture should show its blue half", Color.BLUE, c)
            }
            n++
        }
        assertEquals(deck.slides.size, n)
    }
}
