package io.github.baeseungwon1010.officecanvas.hwp

import android.graphics.Bitmap
import io.github.baeseungwon1010.officecanvas.DocumentFormat
import io.github.baeseungwon1010.officecanvas.hwpx.DrawingKind
import io.github.baeseungwon1010.officecanvas.hwpx.HwpxElement
import io.github.baeseungwon1010.officecanvas.hwpx.HwpxPage
import io.github.baeseungwon1010.officecanvas.hwpx.HwpxRenderer
import io.github.baeseungwon1010.officecanvas.hwpx.ParaAlign
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config
import org.robolectric.annotation.GraphicsMode
import java.io.File

/**
 * sample.hwp is generated by tools/make_sample_hwp.py (records and an OLE2
 * container written directly, since nothing else here can write .hwp): the same
 * three pages of text as sample.hwpx plus a styled title, a filled and centered
 * table cell, a cropped picture, a header with the page number field, a page
 * number, a floating text box, a line and a forced page break.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
@GraphicsMode(GraphicsMode.Mode.NATIVE)
class HwpParserTest {

    private val file by lazy { File(javaClass.classLoader!!.getResource("hwp_samples/sample.hwp")!!.toURI()) }
    private val doc by lazy { HwpParser.parse(file) }

    private fun runs(page: Int) = doc.pages[page].elements.filterIsInstance<HwpxElement.TextRun>()

    @Test
    fun `is detected as HWP by content`() {
        assertEquals(DocumentFormat.HWP, DocumentFormat.detect(file))
    }

    @Test
    fun `pages follow the saved line positions and the page-break flag`() {
        assertEquals(4, doc.pages.size)
        // The last page begins with a paragraph flagged as starting a page whose
        // first line is at the top, like the previous page's.
        assertTrue(runs(3).any { it.text == "3. 맺음말" })
        assertTrue(runs(2).none { it.text == "3. 맺음말" })
    }

    @Test
    fun `page geometry comes from the section definition`() {
        val page = doc.pages[0]
        assertEquals(59528L, page.widthHu)
        assertEquals(84186L, page.heightHu)
        assertEquals(8504L, page.bodyXHu)
        assertEquals(5668L + 4252L, page.bodyYHu)
    }

    @Test
    fun `character and paragraph shapes`() {
        val title = runs(0).first { it.text == "1. 문서 구조와 줄 위치" }
        val style = title.spans.single().style
        assertEquals(16f, style.sizePt, 0.01f)
        assertTrue(style.bold)
        assertEquals(0xFFC00000.toInt(), style.colorArgb)
        assertEquals("함초롬바탕", style.hangulFace)
        assertEquals(ParaAlign.CENTER, title.align)
        val body = runs(0).first { it.text.startsWith("(1)") }
        assertEquals(ParaAlign.JUSTIFY, body.align)
        assertEquals(false, body.lastLine)
    }

    @Test
    fun `header and page number repeat on every page`() {
        // Numbers start over on the last page, and the first page hides its
        // page number (but not the number in its header).
        val numbers = listOf(1, 2, 3, 1)
        for (i in doc.pages.indices) {
            val r = runs(i)
            val n = numbers[i]
            assertTrue("header on page ${i + 1}", r.any { it.text == "OfficeCanvas 머리말\t$n" && it.yHu < 0 })
            assertEquals("page number on page ${i + 1}", i != 0, r.any { it.text == "- $n -" && it.align == ParaAlign.CENTER })
        }
    }

    @Test
    fun `a tab keeps the width Hangul saved for it`() {
        val header = runs(0).first { it.text.startsWith("OfficeCanvas") }
        assertEquals(listOf("OfficeCanvas 머리말", "\t", "1"), header.spans.map { it.text })
        assertEquals(20000L, header.spans[1].tabHu)
    }

    @Test
    fun `numbered paragraphs and bullets get the marks Hangul would draw`() {
        val heads = doc.pages.flatMap { it.elements }.filterIsInstance<HwpxElement.TextRun>()
            .filter { it.text.endsWith("항목") }.map { it.spans.first().text to it.spans.drop(2).joinToString("") { s -> s.text } }
        // Level 1 counts in digits, level 2 in Hangul syllables and restarts under
        // each level-1 paragraph; the bullet is Wingdings' small bullet.
        assertEquals(listOf("1." to "첫째 항목", "가." to "세부 항목", "2." to "둘째 항목", "•" to "점 항목"), heads)
        // The text after the mark is set off by half the text size.
        val first = doc.pages.flatMap { it.elements }.filterIsInstance<HwpxElement.TextRun>().first { it.text.endsWith("첫째 항목") }
        assertEquals((first.spans[0].style.sizePt * 50).toLong(), first.spans[1].tabHu)
    }

    @Test
    fun `an equation in a line of text is part of the line`() {
        val run = doc.pages.flatMap { it.elements }.filterIsInstance<HwpxElement.TextRun>()
            .single { r -> r.spans.any { it.inline is HwpxElement.Equation } }
        assertEquals("사다리꼴의 넓이는", run.spans.first().text.trim())
        val eq = run.spans.last().inline as HwpxElement.Equation
        assertEquals("{a+b} over {2} TIMES h", eq.script)
        assertEquals(6000L, run.spans.last().tabHu)
        assertEquals(70, eq.baselinePercent)
    }

    @Test
    fun `table cells carry fills, vertical alignment and text`() {
        val table = doc.pages.flatMap { it.elements }.filterIsInstance<HwpxElement.Table>().single()
        assertEquals(2, table.cells.size)
        val first = table.cells[0][0]!!
        assertEquals(0xFFDDEBF7.toInt(), first.borderFill?.fillArgb)
        assertEquals(1, first.vAlign)
        assertEquals("형식", first.runs.single().text)
        assertEquals("OLE2 + 레코드", table.cells[1][1]!!.runs.single().text)
        // That cell leaves its margins (0xFFFF) to the table's: 510 left, 141 top.
        assertEquals(510L to 141L, table.cells[1][1]!!.runs.single().let { it.xHu to it.yHu })
    }

    @Test
    fun `a floating text box sits at its offsets from the paragraph`() {
        val page = doc.pages.indexOfFirst { p -> p.elements.any { it is HwpxElement.Drawing && it.kind == DrawingKind.RECTANGLE } }
        val box = doc.pages[page].elements.filterIsInstance<HwpxElement.Drawing>().single { it.kind == DrawingKind.RECTANGLE }
        val anchor = runs(page).first { it.text.startsWith("(9)") }
        assertEquals(42520L - 14000L, box.xHu)
        assertEquals(anchor.yHu + 1500L, box.yHu)
        assertEquals(14000L, box.widthHu)
        assertEquals(4000L, box.heightHu)
        assertEquals(0xFF1F3864.toInt(), box.lineArgb)
        assertEquals(0xFFDDEBF7.toInt(), box.fillArgb)
        assertEquals(20, box.cornerPercent)
        assertEquals(1, box.contentVAlign)
        val text = box.content.filterIsInstance<HwpxElement.TextRun>().single()
        assertEquals("글상자 안의 글", text.text)
        assertEquals(283L, text.xHu) // the left margin
        // A floating object never starts a page or a line: the paragraph after it
        // is still on the same page.
        assertTrue(runs(page).any { it.text.startsWith("(10)") })

        val pixel = render(page).pixelAt(doc.pages[page], box.xHu + box.widthHu - 1500, box.yHu + 600)
        assertColor(listOf(0xDD, 0xEB, 0xF7), pixel)
    }

    @Test
    fun `lines are drawn with their color`() {
        val page = doc.pages.indexOfFirst { p -> p.elements.any { it is HwpxElement.Drawing && it.kind == DrawingKind.LINE } }
        val line = doc.pages[page].elements.filterIsInstance<HwpxElement.Drawing>().single { it.kind == DrawingKind.LINE }
        assertEquals(42520L, line.widthHu)
        assertEquals(listOf(0L to 0L, 42520L to 0L), line.points)
        assertEquals(0xFFC00000.toInt(), line.lineArgb)
        assertColor(listOf(0xC0, 0, 0), render(page, 4000).pixelAt(doc.pages[page], line.xHu + 20000, line.yHu))
    }

    @Test
    fun `pictures come from BinData and are drawn`() {
        val image = doc.pages.flatMap { it.elements }.filterIsInstance<HwpxElement.ImageEl>().single()
        val png = image.bytes!!
        assertEquals(0x89.toByte(), png[0])
        assertEquals('P'.code.toByte(), png[1])

        // The picture keeps only the right (blue) half of the image, given within
        // the image's own size at the end of the record, so its left quarter is blue too.
        val crop = image.crop!!
        assertEquals(0.5f, crop.left, 0.001f)
        assertEquals(0f, crop.right, 0.001f)
        val page = doc.pages.indexOfFirst { image in it.elements }
        val pixel = render(page).pixelAt(doc.pages[page], image.xHu + image.widthHu / 4, image.yHu + image.heightHu / 2)
        assertColor(listOf(0x3A, 0x5B, 0xA0), pixel)
    }

    private fun render(page: Int, longSide: Int = 1000): Bitmap {
        var bitmap: Bitmap? = null
        HwpxRenderer.render(doc.copy(pages = listOf(doc.pages[page])), file, longSide) { _, b -> bitmap = b }
        return bitmap!!
    }

    /** The pixel at body coordinates ([x], [y] in HWPUNIT) of a rendered page. */
    private fun Bitmap.pixelAt(p: HwpxPage, x: Long, y: Long): Int {
        val scale = height.toDouble() / p.heightHu
        return getPixel(((p.bodyXHu + x) * scale).toInt(), ((p.bodyYHu + y) * scale).toInt())
    }

    private fun assertColor(expected: List<Int>, pixel: Int) {
        val actual = listOf((pixel shr 16) and 0xFF, (pixel shr 8) and 0xFF, pixel and 0xFF)
        assertTrue("pixel $actual, expected $expected", expected.zip(actual).all { (e, a) -> kotlin.math.abs(e - a) <= 6 })
    }
}
